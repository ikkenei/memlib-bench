#!/bin/sh
# Generate a C header embedding the benchmark size distributions.
#
# Usage: gen_distributions.sh OUT.h file1.csv [file2.csv ...]
#
# Each CSV becomes a string constant (long lines are split into C string
# literals, so the compiler's literal length limit is not exceeded) and a
# table entry mapping the file base name to the data.

set -e

out=$1
shift

if [ $# -eq 0 ]; then
    echo "usage: $0 OUT.h FILE.csv ..." >&2
    exit 2
fi

tmp=$out.tmp
{
    echo "/* Generated by tools/gen_distributions.sh - do not edit. */"
    echo "struct mb_dist_entry { const char *name; const char *csv; };"

    i=0
    for f in "$@"; do
        i=$((i + 1))
        awk -v idx="$i" '
            BEGIN { printf "static const char mb_dist_data_%d[] =\n", idx }
            {
                line = $0
                gsub(/\\/, "\\\\", line)
                gsub(/"/, "\\\"", line)
                # Split long lines into chunks, but keep the content exact:
                # only the real end of the line gets a newline.
                while (length(line) > 900) {
                    printf "\"%s\"\n", substr(line, 1, 900)
                    line = substr(line, 901)
                }
                printf "\"%s\\n\"\n", line
            }
            END { print ";" }
        ' "$f"
    done

    echo "static const struct mb_dist_entry mb_dist_table[] = {"
    i=0
    for f in "$@"; do
        i=$((i + 1))
        base=$(basename "$f" .csv)
        echo "  { \"$base\", mb_dist_data_$i },"
    done
    echo "};"
    echo "#define MB_DIST_TABLE_SIZE $i"
} > "$tmp"
mv -f "$tmp" "$out"
